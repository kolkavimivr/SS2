<?php
header("Content-Type: text/plain; charset=UTF-8");

// קליטת פרמטרים בסיסיים מימות המשיח
$phone     = $_GET['ApiPhone'] ?? 'anonymous';
$step      = isset($_GET['step']) ? intval($_GET['step']) : 0;
$user_val  = $_GET['val'] ?? '';

// קליטת תשובות קודמות שנשמרו בשיחה
$q16 = $_GET['q16'] ?? '';
$q17 = $_GET['q17'] ?? '';
$q18 = $_GET['q18'] ?? '';

// ------------------------------------------------------------------
// לוגיקת ניתוח השלבים
// ------------------------------------------------------------------

// שלב 0: השמעת פתיח ומעבר לשאלה הראשונה
if ($step === 0) {
    // read=f-quiz_intro=val,no,1,1,7,Stt,no,1,2,3
    echo "read=f-quiz_intro=val,no,1,1,5,Stt,no,1,2,3&step=1";
    exit;
}

// שלבים 1 עד 15: שאלות חלק א' וב' (השמעת v001.wav עד v015.wav)
if ($step >= 1 && $step <= 15) {
    $next_step = $step + 1;
    $file_num  = sprintf("%03d", $step); // הופך ל-001, 002...
    echo "read=f-v{$file_num}=val,no,1,1,5,Stt,no,1,2,3&step={$next_step}&q16={$q16}&q17={$q17}&q18={$q18}";
    exit;
}

// שלב 16: שאלה 16 (נטייה חברתית)
if ($step === 16) {
    // אם זו פעם ראשונה שנכנסים לשלב 16 - משמיעים את שאלה 16 ומקבלים ערך
    if (!isset($_GET['val'])) {
        echo "read=f-v016=val,no,1,1,5,Stt,no,1,2,3&step=16&q16={$q16}&q17={$q17}&q18={$q18}";
        exit;
    }
    // שמירת התשובה של שאלה 16 ומעבר לשאלה 17
    $q16 = $user_val;
    echo "read=f-v017=val,no,1,1,5,Stt,no,1,2,3&step=17&q16={$q16}&q17={$q17}&q18={$q18}";
    exit;
}

// שלב 17: שאלה 17 (עומס מינימלי)
if ($step === 17) {
    $q17 = $user_val;
    echo "read=f-v018=val,no,1,1,5,Stt,no,1,2,3&step=18&q16={$q16}&q17={$q17}&q18={$q18}";
    exit;
}

// שלב 18: שאלה 18 (קונפורמיזם) ושיוך סיכום
if ($step === 18) {
    $q18 = $user_val;

    // --------------------------------------------------------------
    // חישוב המשוב המותאם לפי חלק ג'
    // --------------------------------------------------------------
    $feedback_file = "info_independent"; // ברירת מחדל

    if ($q16 === "1" || $q18 === "1") {
        // זיהוי בחירה חברתית / קונפורמיזם -> השמעת אזהרה
        $feedback_file = "warning_social";
    } elseif ($q17 === "1") {
        // זיהוי צורך בעומס מינימלי -> השמעת מידע על שיווק/משאבי אנוש
        $feedback_file = "info_minimal_load";
    }

    // --------------------------------------------------------------
    // שליחת הנתונים ל-Google Sheets (אופציונלי - במידה ויש Webhook)
    // --------------------------------------------------------------
    $webHookUrl = "https://script.google.com/macros/s/YOUR_SCRIPT_ID/exec";
    if (!empty($webHookUrl)) {
        @file_get_contents($webHookUrl . "?phone={$phone}&q16={$q16}&q17={$q17}&q18={$q18}&feedback={$feedback_file}");
    }

    // --------------------------------------------------------------
    // החזרת פקודת השמעה סופית לתלמידה
    // --------------------------------------------------------------
    echo "id_list_message=f-{$feedback_file}&go_to_folder=/0/3";
    exit;
}                                                                                          
?>
